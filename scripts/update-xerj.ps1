# scripts/update-xerj.ps1
# Automates fetching upstream XERJ, cleaning, applying patches, and running verification.

param(
    [Parameter(Mandatory = $true, HelpMessage = "上游 Release Tag，例如: v1.0.0-rc.102")]
    [string]$Tag,
    [string]$Repo = "https://github.com/xerj-org/xerj.git"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("xerj-" + [guid]::NewGuid().ToString("N"))
$target = Join-Path $root "crates/xerj"
$patchDir = Join-Path $root "patches"

Write-Host "==========================================================" -ForegroundColor Magenta
Write-Host "     XERJ 官方源码平滑升级流水线 (Tag: $Tag)" -ForegroundColor Magenta
Write-Host "==========================================================" -ForegroundColor Magenta

try {
    Write-Host "`n==> [1/5] 正在拉取 XERJ 官方仓库 ($Repo, Tag: $Tag)..." -ForegroundColor Cyan
    git clone --depth 1 --branch $Tag $Repo $tmp
    if ($LASTEXITCODE -ne 0) {
        throw "克隆上游代码库失败，请检查 Tag 名称或网络连接。"
    }

    $commit = (git -C $tmp rev-parse HEAD).Trim()
    Write-Host "    成功拉取最新源码，Commit SHA: $commit" -ForegroundColor Green

    Write-Host "`n==> [2/5] 正在替换 crates/xerj 目录源码胶囊..." -ForegroundColor Cyan
    if (Test-Path $target) {
        Remove-Item -Recurse -Force $target
    }
    New-Item -ItemType Directory -Force -Path $target | Out-Null

    Copy-Item (Join-Path $tmp "LICENSE") (Join-Path $target "LICENSE")
    Copy-Item (Join-Path $tmp "NOTICE") (Join-Path $target "NOTICE")
    Copy-Item (Join-Path $tmp "README.md") (Join-Path $target "README.md")
    Copy-Item -Recurse (Join-Path $tmp "engine") (Join-Path $target "engine")
    Copy-Item -Recurse (Join-Path $tmp "xerj-ux") (Join-Path $target "xerj-ux")
    Write-Host "    源码与控制台资产更新完成。" -ForegroundColor Green

    Write-Host "`n==> [3/5] 正在逐一重放定制 Patch 补丁..." -ForegroundColor Cyan
    $patches = Get-ChildItem $patchDir -Filter *.patch | Sort-Object Name
    foreach ($patch in $patches) {
        Write-Host "    -> 应用补丁: $($patch.Name)..." -NoNewline
        try {
            git apply --directory="crates/xerj" $patch.FullName
            Write-Host " [成功]" -ForegroundColor Green
        }
        catch {
            Write-Host " [冲突失败]" -ForegroundColor Red
            Write-Host "`n❌ 补丁应用发生冲突: $($patch.Name)" -ForegroundColor Red
            Write-Host "请按以下步骤处理重新导出补丁 (Re-patch):" -ForegroundColor Yellow
            Write-Host "  1. 执行: git apply --directory='crates/xerj' --reject '$($patch.FullName)'" -ForegroundColor Yellow
            Write-Host "  2. 检查 .rej 文件并手工调整 crates/xerj 对应文件上下文" -ForegroundColor Yellow
            Write-Host "  3. 重新导出补丁并覆盖 patches 目录下的对应 patch 文件" -ForegroundColor Yellow
            throw "补丁 $($patch.Name) 冲突，升级流程中断。"
        }
    }

    Write-Host "`n==> [4/5] 写入上游版本追踪元数据 (UPSTREAM_VERSION)..." -ForegroundColor Cyan
    $fetchedDate = (Get-Date -Format o)
    $upstreamContent = @"
# XERJ Upstream Tracking Metadata (Auto-generated by scripts/update-xerj.ps1)
repository = "$Repo"
tag = "$Tag"
commit = "$commit"
fetched_at = "$fetchedDate"
license = "Apache-2.0"
patch_series = "patches"
"@
    Set-Content -Path (Join-Path $patchDir "upstream.toml") -Value $upstreamContent -Encoding UTF8
    Set-Content -Path (Join-Path $target "UPSTREAM_VERSION") -Value $upstreamContent -Encoding UTF8
    Write-Host "    已更新 patches/upstream.toml 与 crates/xerj/UPSTREAM_VERSION" -ForegroundColor Green

    Write-Host "`n==> [5/5] 执行全套完整性与防腐层校验..." -ForegroundColor Cyan
    & (Join-Path $PSScriptRoot "verify-xerj.ps1")

    Write-Host "`n🎉 XERJ 升级完成！建议继续执行以下全量验证:" -ForegroundColor Magenta
    Write-Host "  cargo test -p adapter" -ForegroundColor White
    Write-Host "  cargo test -p xcat-mcp" -ForegroundColor White
    Write-Host "  cargo test --workspace" -ForegroundColor White
}
finally {
    if (Test-Path $tmp) {
        Remove-Item -Recurse -Force $tmp
    }
}
